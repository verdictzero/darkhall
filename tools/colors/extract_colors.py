#!/usr/bin/env python3
"""Extracts the camera colour table from LibRaw's src/tables/colordata.cpp.

Usage: extract_colors.py path/to/colordata.cpp > core/src/main/resources/darkhall/camera_colors.tsv

Each output row: maker, model prefix, black override, white override, then the XYZ->camera
matrix (Adobe DNG ColorMatrix for D65, x10000). Rows keep LibRaw's order because lookups take
the first matching prefix. The matrices come from Adobe DNG Converter via LibRaw
(LGPL-2.1 / CDDL-1.0); see README.
"""
import re, sys

src = open(sys.argv[1], encoding='utf8').read()
body = src[src.index('table[] = {'):src.index('  };', src.index('table[] = {'))]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
body = re.sub(r'^\s*#[^\n]*', '', body, flags=re.M)
rows = re.findall(r'\{\s*LIBRAW_CAMERAMAKER_(\w+)\s*,\s*"([^"]*)"\s*,\s*(-?\w+)\s*,\s*(-?\w+)\s*,\s*\{([-\d\s,]*)\}\s*\}', body)
assert len(rows) == body.count('LIBRAW_CAMERAMAKER_'), (len(rows), body.count('LIBRAW_CAMERAMAKER_'))
print('# maker\tprefix\tblack\twhite\txyz_to_cam x10000 (generated by tools/colors/extract_colors.py from LibRaw)')
for maker, prefix, black, white, m in rows:
    vals = [int(v, 0) for v in m.replace('\n', ' ').split(',') if v.strip()]
    vals = (vals + [0] * 9)[:9]
    print(f'{maker}\t{prefix}\t{int(black, 0)}\t{int(white, 0)}\t' + ','.join(map(str, vals)))
