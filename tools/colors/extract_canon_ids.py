#!/usr/bin/env python3
"""Extracts Canon's ModelID -> international model name table from LibRaw.

Usage: extract_canon_ids.py LIBRAW_DIR > core/src/main/resources/darkhall/canon_models.tsv

The EXIF model of a Canon may be its US ("Rebel T7i") or Japanese ("Kiss X9i") name; the
MakerNote ModelID (tag 0x10) identifies the body, and the colour table uses the
international name (LibRaw's normalize_model.cpp, LGPL-2.1 / CDDL-1.0).
"""
import os, re, sys

root = sys.argv[1]
ids = {}
for name, expr in re.findall(r'#define\s+(CanonID_\w+)\s+\(?([^\n]*?)\)?\s*$',
                             open(os.path.join(root, 'internal/libraw_cameraids.h')).read(), re.M):
    try:
        ids[name] = eval(expr.replace('ULL', '').replace('LL', ''))
    except Exception:
        pass
src = open(os.path.join(root, 'src/metadata/normalize_model.cpp')).read()
print('# Data from LibRaw 0.22.1 (internal/libraw_cameraids.h, src/metadata/normalize_model.cpp), Copyright 2008-2025 LibRaw LLC,')
print('# used under the Common Development and Distribution License 1.0 (LICENSES/CDDL-1.0.txt).')
print('# Source code: https://github.com/verdictzero/darkhall. See NOTICE.md.')
print('# canon ModelID (hex)\tmodel (generated by tools/colors/extract_canon_ids.py from LibRaw)')
for name, model in re.findall(r'\{\s*(CanonID_\w+)\s*,\s*"([^"]+)"\s*\}', src):
    if name in ids:
        print(f'{ids[name]:x}\t{model}')
